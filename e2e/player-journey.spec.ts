test('window move, resize, minimize, restore and maximize survive save and resume', async ({ page }) => {
  const errors = watchErrors(page)
  await startCase(page)
  await openApp(page, '我的文件')
  const window = page.getByRole('dialog', { name: '我的文件' })
  const titlebar = window.locator('.window-titlebar')
  const titleBox = await titlebar.boundingBox()
  if (!titleBox) throw new Error('File window titlebar was not measurable')
  await page.mouse.move(titleBox.x + 180, titleBox.y + 15)
  await page.mouse.down()
  await page.mouse.move(titleBox.x + 260, titleBox.y + 65, { steps: 4 })
  await page.mouse.up()
  const resize = window.locator('.resize-se')
  const resizeBox = await resize.boundingBox()
  if (!resizeBox) throw new Error('File window resize handle was not measurable')
  await page.mouse.move(resizeBox.x + 2, resizeBox.y + 2)
  await page.mouse.down()
  await page.mouse.move(resizeBox.x + 72, resizeBox.y + 52, { steps: 4 })
  await page.mouse.up()
  const movedBox = await window.boundingBox()
  await page.getByRole('button', { name: '最小化 我的文件', exact: true }).click()
  await expect(window).toBeHidden()
  await page.getByRole('button', { name: '恢复 我的文件' }).click()
  await expect(window).toBeVisible()
  await page.getByRole('button', { name: '最大化 我的文件' }).click()
  await expect(page.getByRole('button', { name: '还原 我的文件' })).toBeVisible()
  await page.keyboard.press('Escape')
  await page.getByRole('menuitem', { name: /保存并返回档案馆/ }).click()
  await page.getByRole('button', { name: '继续调查' }).click()
  await expect(page.getByRole('dialog', { name: '我的文件' })).toBeVisible()
  await expect(page.getByRole('button', { name: '还原 我的文件' })).toBeVisible()
  await titlebar.dblclick()
  const restoredBox = await window.boundingBox()
  expect(Math.abs((restoredBox?.width ?? 0) - (movedBox?.width ?? 0))).toBeLessThan(8)
  expect(errors).toEqual([])
})

